from importlib import metadata, resources
from pathlib import Path

import click
from click.testing import CliRunner

REPO = Path(__file__).resolve().parents[1]
DOCS = REPO / "docs"
WIDTH = 100
CLICK = metadata.version("click")
EXIT_CODE_TEXT = {
    "OK": "success",
    "INTERNAL": "unexpected internal error (`-v` prints the traceback)",
    "USAGE": "usage error: an unknown option, a missing argument",
    "GATE": "the verdict is at or above the level given with `run --fail-on`",
    "INPUT": "an input was not found, not readable or not recognised",
    "PARTIAL": "finished, but a root, a run or a file was skipped or failed",
    "LIBRARY": "library problem: not a library, a newer layout, not writable",
    "VALIDATION": "validation failed",
    "RESOURCE": "a resource limit was exceeded",
    "INTERRUPTED": "interrupted; what was finished is kept",
}


# --------------------------------------------------------------------------------------------- commands
def help_text(args: list[str]) -> str:
    """The text ``flowcellar <args> --help`` prints on a terminal 100 columns wide."""
    from flowcellar.cli import cli
    result = CliRunner().invoke(cli, [*args, "--help"], prog_name="flowcellar", terminal_width=WIDTH)
    if result.exit_code != 0:
        raise SystemExit(f"flowcellar {' '.join(args)} --help failed: {result.output}")
    return "\n".join(line.rstrip() for line in result.output.rstrip().splitlines())


def command_names() -> list[str]:
    from flowcellar.cli import cli
    return list(cli.list_commands(click.Context(cli)))


def commands_page() -> str:
    from flowcellar import __version__
    from flowcellar.cli import cli
    from flowcellar.util.errors import ExitCode
    names = command_names()
    ctx = click.Context(cli)
    out = [
        f"<!-- Generated by tools/build_docs.py from `flowcellar --help` (click {CLICK}). "
        "Do not edit: change the help text in src/flowcellar/cli and run the tool. -->",
        "# Commands",
        "",
        f"Every block on this page is what the command prints with `--help`, word for word (FlowCellar "
        f"{__version__.split('.dev')[0]}).",
        "No command contacts the network and no command asks a question. Progress and notices go to standard",
        "error, one line each; results go to standard output.",
        "",
        "| Command | What it does |",
        "|---|---|",
    ]
    for name in names:
        cmd = cli.get_command(ctx, name)
        out.append(f"| [`{name}`](#flowcellar-{name}) | {cmd.get_short_help_str(limit=200)} |")
    out += ["", "## Global options", "", "They go before the command name. `-L` is also accepted after it.", "",
            "```text", help_text([]), "```", ""]
    for name in names:
        out += [f"## flowcellar {name}", "", "```text", help_text([name]), "```", ""]
    out += [
        "## Exit codes",
        "",
        "| Code | Meaning |",
        "|---|---|",
    ]
    for code in ExitCode:
        out.append(f"| {int(code)} | {EXIT_CODE_TEXT[code.name]} |")
    out += [
        "",
        "## Searching: `ls --where`",
        "",
        "`ls --where` uses the search of the hub's Runs table. Every term must match. A plain word matches any",
        "text of a run (ids, names, kit, project, samples); `field:value` matches one column, with a comma for",
        "\"any of\"; numbers take comparisons and units; a `-` in front excludes.",
        "",
        "```text",
        "status:warn,fail          runs with a warning or a failure",
        "kit:SQK-PCB114-24         one kit",
        "project:alpha             one project",
        "yield:>50gb               more than 50 Gb estimated",
        "after:2026-01-01          started on or after a date;  year:2026  last:90d",
        "-status:pass              everything that did not pass",
        "```",
        "",
        "## Files a command writes",
        "",
        "| File | Written by | What it is |",
        "|---|---|---|",
        "| `<prefix>.fcb.json.gz` | `run` | the bundle of one run with its verdict: gzip-compressed JSON that "
        "follows the schema `flowcellar schema` prints |",
        "| `<prefix>.flowcellar.html` | `run`, `hub --reports` | one self-contained page; opens from a file and "
        "makes no request |",
        "| `<library>/hub/index.html` | `scan`, `hub` | the library's pages; `index.js` and `data/<run key>.js` "
        "beside it hold the data |",
        "| everything else under `<library>/` | `scan`, `run -L`, `rm`, `recompute` | see [The library](library.md) |",
        "",
    ]
    return "\n".join(out)


# ---------------------------------------------------------------------------------------------- metrics
ASSAY = {"gdna": "genomic DNA", "cdna": "cDNA", "drna": "direct RNA"}
FAMILY = {"promethion": "PromethION", "minion": "MinION / GridION", "flongle": "Flongle"}
CHEMISTRY = {"r10": "R10", "r9": "R9", "rna004": "RNA004"}
ROLE = {"key": "key", "supporting": "supporting", "info": "shown only"}
BUILT_MODULES = ("run", "fc", "yield", "dyn", "len", "qual", "aln", "cdna", "rna", "funnel")
SC_PIPELINE = {"spaceranger": "Space Ranger", "wf-single-cell": "wf-single-cell"}


def _num(v: float, unit: str) -> str:
    if unit == "Q":
        return f"Q {v:g}"
    if unit == "degC":
        return f"{v:g} °C"
    if unit in ("bases", "reads"):
        if v >= 1e9:
            return f"{v / 1e9:g} G{'b' if unit == 'bases' else ' reads'}"
        if v >= 1e6:
            return f"{v / 1e6:g} M{'b' if unit == 'bases' else ' reads'}"
        return f"{v:,.0f} {unit}"
    if unit == "" and 0 < v <= 1:
        return f"{v * 100:.4g} %"
    return f"{v:,.0f}" if float(v).is_integer() else f"{v:g}"


def _when(when: dict) -> str:
    parts = []
    if "family" in when:
        parts.append(FAMILY.get(when["family"], when["family"]))
    if "assay" in when:
        parts.append(ASSAY.get(when["assay"], when["assay"]))
    if "chemistry" in when:
        parts.append(CHEMISTRY.get(when["chemistry"], when["chemistry"]))
    if "model_tier" in when:
        parts.append(f"{when['model_tier']} model")
    return ", ".join(parts) if parts else "every run"


def _limits(metric: dict) -> str:
    th = metric.get("thresholds") or {}
    kind, rules = th.get("kind"), th.get("rules") or []
    key = metric.get("verdict_role") == "key"
    if kind in ("min", "max") and rules:
        word = "below" if kind == "min" else "above"
        cells = []
        for r in rules:
            text = f"{_when(r.get('when') or {})}: warning {word} {_num(r['warn'], metric.get('unit') or '')}"
            if key and r.get("fail") is not None:
                text += f", fail {word} {_num(r['fail'], metric.get('unit') or '')}"
            cells.append(text)
        return "<br>".join(cells)
    if kind == "run_config":
        return "the target range of the run's own kit, as MinKNOW recorded it"
    if kind == "baseline":
        return "the lab's own history"
    if kind == "rule":
        return "a written-out rule (see How to read)"
    return "none"


def _row(metric: dict, label: str | None = None, mark: str = "") -> str:
    d = metric.get("display") or {}
    how = (d.get("how_to_read") or metric.get("meaning") or "").replace("|", "/").replace("\n", " ").rstrip(".") + "."
    cells = [mark + (label or d.get("label") or metric["id"]), f"`{metric['id']}`", ROLE[metric.get("verdict_role", "info")],
             _limits(metric), how]
    return "| " + " | ".join(cells) + " |"


def _sc_number(v: float, unit: str) -> str:
    if unit == "fraction":
        return f"{v * 100:g} %"
    return f"{v:,.0f}" if float(v).is_integer() and abs(v) >= 10 else f"{v:g}"


def _sc_limits(check: dict, metric: dict) -> str:
    """The default limits of one check of the single-cell and spatial add-on, in words."""
    th = dict(metric.get("thresholds") or {}) if isinstance(metric.get("thresholds"), dict) else {}
    for k in ("warn", "fail"):
        if isinstance(check.get(k + "_at"), (int, float)):
            th[k] = check[k + "_at"]
    unit, key = metric.get("unit") or "", check.get("role") == "key"
    if check.get("kind") == "range" and isinstance(th.get("warn_low"), (int, float)) and isinstance(th.get("warn_high"), (int, float)):
        return f"warning outside {_sc_number(th['warn_low'], unit)} to {_sc_number(th['warn_high'], unit)}"
    if check.get("kind") in ("min", "max") and isinstance(th.get("warn"), (int, float)):
        word = "below" if check["kind"] == "min" else "above"
        # a check whose number is a share inside a table (unit "table") still has a share as its limit
        u = "fraction" if unit in ("table", "") and 0 < th["warn"] <= 1 else unit
        text = f"warning {word} {_sc_number(th['warn'], u)}"
        if key and isinstance(th.get("fail"), (int, float)):
            text += f", fail {word} {_sc_number(th['fail'], u)}"
        return text
    return "a written-out rule (see How to read)"


def sc_section() -> list[str]:
    """The checks and the labelled numbers of the single-cell and spatial add-on, from its own catalogue."""
    from flowcellar.sc import catalogue as sc
    cat = sc.load()
    out = [
        "",
        "## Single-cell and spatial analyses",
        "",
        "An analysis (an output folder of wf-single-cell or of Space Ranger) has a verdict of its own, made the same",
        "way: the worst of its checks, key checks can fail it, supporting checks can warn. It never changes the",
        "verdict of a flow cell run, and a flow cell run that is not in the library never lowers the verdict of an",
        "analysis. A number whose source is missing is not available, never a failure, and a number",
        "taken from a pipeline's report is marked \"from report\" on the page. The alarms a pipeline raises itself are",
        f"quoted word for word. This part is written from the add-on's catalogue, version {sc.version()}",
        "(`catalogue/metrics_singlecell_spatial.yaml`); its limits are first proposals, not tuned on any history.",
        "",
        "| Check | Id | Role | From | Default limits | How to read |",
        "|---|---|---|---|---|---|",
    ]
    for check in sc.checks():
        m = sc.metric(check["id"]) or {}
        d = m.get("display") or {}
        how = (d.get("how_to_read") or m.get("meaning") or "").replace("|", "/").replace("\n", " ").rstrip(".") + "."
        out.append("| " + " | ".join([d.get("label") or m.get("name") or check["id"], f"`{check['id']}`", ROLE[check.get("role", "info")],
                                      SC_PIPELINE.get(check.get("pipeline"), "both pipelines"), _sc_limits(check, m), how]) + " |")
    out += ["", "### The numbers of an analysis", "", "| Label | Id | Unit |", "|---|---|---|"]
    checked = {c["id"] for c in sc.checks()}
    for m in cat["metrics"]:
        if m["id"] in checked:
            continue
        label = (m.get("display") or {}).get("label") or m.get("name")
        unit = {"fraction": "share"}.get(m.get("unit") or "", m.get("unit") or "")
        out.append(f"| {label} | `{m['id']}` | {unit} |")
    out.append("")
    return out


def _unit(metric: dict) -> str:
    unit = metric.get("unit") or ""
    if unit == "fraction" or (not unit and metric["id"].endswith("_frac")):
        return "share"
    return {"degC": "°C", "h": "hours", "s": "seconds", "bases per s": "bases per second"}.get(unit, unit)


def metrics_page() -> str:
    from flowcellar import catalogue
    from flowcellar.engine.limits import FIXED_CHECKS, HORIZONS, PENDING, RULE_CHECKS
    from flowcellar.readdata.copy_pending import CHECK_FORMAT
    cat = catalogue.load()
    base = tomllib.loads(resources.files("flowcellar.config").joinpath("defaults.toml").read_text("utf-8"))["baselines"]
    roles = cat["conventions"]["verdict_role"]
    health = [catalogue.metric(i) for i in (*RULE_CHECKS, *FIXED_CHECKS)]
    # a read-data check is stored under the id of its check; one of them judges a number with an id of its own
    judged_as = {"aln_identity_median": "aln_identity_hist"}
    read_ids = [judged_as.get(i, i) for i in CHECK_FORMAT]
    read = [catalogue.metric(i) for i in read_ids]
    read_labels = {judged_as[i]: catalogue.label(i) for i in CHECK_FORMAT if i in judged_as}
    missing = [i for i, m in zip((*RULE_CHECKS, *FIXED_CHECKS, *read_ids), (*health, *read)) if m is None]
    if missing:
        raise SystemExit(f"the catalogue has no entry for: {', '.join(missing)}")
    horizons = sorted(HORIZONS)
    out_reads = catalogue.metric(f"yield_reads_at_{max(horizons)}h")
    out_bases = catalogue.metric(f"yield_estimated_bases_at_{max(horizons)}h")
    out = [
        "<!-- Generated by tools/build_docs.py from the metric catalogue inside the package. "
        "Do not edit: change catalogue/metrics_nanopore.yaml and run the tools. -->",
        "# The metric catalogue",
        "",
        "Every number FlowCellar shows has one entry in the **metric catalogue**: its id, its label, how to read",
        "it, and, for a check, its limits. The viewer takes its labels from it and the verdicts take their limits",
        f"and sentences from it. This page is written from catalogue version {catalogue.version()}.",
        "",
        "- Source: `catalogue/metrics_nanopore.yaml` in the repository.",
        "- In the package: `flowcellar/catalogue/metrics_nanopore.json`. Read it with",
        "  `python -c \"from flowcellar import catalogue; print(catalogue.metric('fc_occupancy_first_hour'))\"`.",
        "",
        "## How a number becomes a verdict",
        "",
        "A run gets one of **Pass**, **Warning**, **Fail**, **Incomplete** or **Running**, in two parts: **Run",
        "health** (from MinKNOW's own files) and **Read data** (from the reads). Each part is the worst of its",
        "checks, and a check has one of three roles:",
        "",
        "| Role | What it can do |",
        "|---|---|",
        f"| key | {roles['key']} |",
        f"| supporting | {roles['supporting']} |",
        f"| shown only | {roles['info']} |",
        "",
        "A limit is one of these kinds:",
        "",
        "- **fixed level**: \"warning below 70 %\". The levels in the tables below are the defaults; a library can",
        "  change any of them (see the end of this page).",
        "- **the run's own target**: the speed range the kit asks for, read from the run's files.",
        "- **the lab's own history**: the run is placed against the earlier runs of the same kind in the same",
        "  library (same device type, flow cell type and kit), as they were on the day the run started. History",
        f"  is used from {base['min_runs']} comparable runs, can warn but not fail until there are {base['trusted_runs']}, and is not used for a",
        "  verdict when the comparable runs differ widely from each other. A verdict is not changed by runs that",
        "  come later.",
        "- **a written-out rule**: for example \"the run was ended by the instrument\".",
        "",
        "A check that cannot be assessed (no limit for this kind of run, the reads are not counted yet, the files",
        "hold a different set of reads than the check is written for) says so with its reason; it never counts as",
        "passed or failed.",
        "",
        "## Run health",
        "",
        "From the run folder alone; no basecalling is needed. The checks marked with * wait until the reads of the",
        "run have been counted (\"full detail\").",
        "",
        "| Check | Id | Role | Default limits | How to read |",
        "|---|---|---|---|---|",
    ]
    out += [_row(m, mark="* " if m["id"] in PENDING else "") for m in health]
    factors = (out_reads.get("thresholds") or {}).get("horizon_factors") or {}
    out += [
        "",
        "### Output",
        "",
        "The output of a run is judged at the last fixed time it reached ("
        + ", ".join(f"{h} h" for h in horizons) + "), so that runs of different",
        "length can be compared. The unit is reads for cDNA and direct RNA and estimated bases for genomic DNA,",
        "unless the library's configuration sets `outcome_unit`. A run of under one hour is Incomplete. From one to",
        "six hours the checks above apply but the output is not judged: the run is a Warning or a Fail when a check",
        "says so, and Incomplete otherwise.",
        "",
        "- With enough lab history the output is placed against it: a warning well below what is typical here,",
        f"  a fail far below it once the history rests on {base['trusted_runs']} comparable runs.",
        "- Without history these fixed levels apply. They are stated for " + f"{max(horizons)} h" + " and scaled to the earlier times.",
        "",
        "| Output | Id | Fixed levels at " + f"{max(horizons)} h" + " |",
        "|---|---|---|",
        f"| {out_reads['display']['label'].rsplit(' at ', 1)[0]} | `yield_reads_at_<hours>h` | {_limits(dict(out_reads, thresholds=dict(out_reads['thresholds'], kind='min')))} |",
        f"| {out_bases['display']['label'].rsplit(' at ', 1)[0]} | `yield_estimated_bases_at_<hours>h` | {_limits(dict(out_bases, thresholds=dict(out_bases['thresholds'], kind='min')))} |",
        "",
        "Share of the " + f"{max(horizons)} h" + " level that applies at an earlier time:",
        "",
        "| Assay | " + " | ".join(f"{h} h" for h in horizons) + " |",
        "|---|" + "---|" * len(horizons),
    ]
    for assay, f in factors.items():
        out.append(f"| {ASSAY.get(assay, assay)} | " + " | ".join(f"{float(f[str(h)]) * 100:g} %" for h in horizons) + " |")
    out += [
        "",
        "On a flow cell that was loaded before, the run cannot be compared with fresh flow cells. Its output is",
        "then judged as estimated bases per starting pore, against the lab's history of that number.",
        "",
        "Other numbers are placed against the lab's history to explain a verdict (pores at the first scan,",
        "occupancy over the first 24 h, pores left after 24 h, time spent sequencing, output per pore, output per",
        "working channel-hour, speed, adapter share). They show as \"differs from typical\" and never change the",
        "verdict of a run on a fresh flow cell.",
        "",
        "## Read data",
        "",
        "From the basecalled and aligned reads, when FlowCellar finds them. Every read is counted. A check is",
        "assessed only on the set of reads it is written for: a share of passed reads, for instance, needs a file",
        "that still holds the reads that failed. Checks on samples are assessed per sample; the worst sample",
        "decides and the sentence names the samples.",
        "",
        "| Check | Id | Role | Default limits | How to read |",
        "|---|---|---|---|---|",
    ]
    out += [_row(m, label=read_labels.get(m["id"])) for m in read]
    built = [m for m in cat["metrics"] if m["module"] in BUILT_MODULES]
    labelled = [m for m in built if (m.get("display") or {}).get("label")]
    derived = [d for d in cat.get("derived", []) if (d.get("display") or {}).get("label")]
    titles = {m["id"]: m["title"] for m in cat["modules"]}
    out += [
        "",
        "## Changing a limit",
        "",
        "The limits of the run health checks are changed per assay group (`gdna`, `cdna`, `drna`) in the library's",
        "`flowcellar.toml`. The limits of the read data checks are the defaults above; this version has no setting",
        "for them.",
        "",
        "```toml",
        "[profiles.cdna.rules.fc_occupancy_first_hour]",
        "warn = 0.65            # a share is written as a fraction",
        "# fail = 0.4           role = \"supporting\"           enabled = false",
        "```",
        "",
        "Then judge the runs again; no input is read: `flowcellar recompute --status-only --all -L DIR`.",
        "See [Configuration](configuration.md).",
        "",
        "## The numbers with a label",
        "",
        f"The catalogue describes {len(cat['metrics'])} metrics and {len(cat.get('derived', []))} numbers derived from them. "
        f"It was written for the whole design, so it",
        "also holds parts that this version does not compute: barcode balance, what is particular to direct RNA,",
        "modified bases, adaptive sampling and duplex. The tables below list the numbers of the parts",
        "that are built and that carry a label in the viewer. A number without a label is shown under a name made",
        "from its id.",
        "",
    ]
    for module in BUILT_MODULES:
        rows = [m for m in labelled if m["module"] == module] + [d for d in derived if d["module"] == module]
        if not rows:
            continue
        out += [f"### {titles.get(module, module)}", "", "| Label | Id | Unit |", "|---|---|---|"]
        out += [f"| {m['display']['label']} | `{m['id']}` | {_unit(m)} |" for m in rows]
        out.append("")
    out += sc_section()
    return "\n".join(out)


PAGES = {"commands.md": commands_page, "metrics.md": metrics_page}


def main(argv: list[str]) -> int:
    stale = []
    for name, make in PAGES.items():
        text = make()
        path = DOCS / name
        if "--check" in argv:
            if not path.exists() or path.read_text("utf-8") != text:
                stale.append(name)
            continue
        path.write_text(text, "utf-8", newline="\n")
        print(f"wrote docs/{name} ({len(text.splitlines())} lines)")
    if stale:
        print(f"not up to date: {', '.join('docs/' + s for s in stale)}; run python tools/build_docs.py "
              f"(help layout follows the installed click, here {CLICK})", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
