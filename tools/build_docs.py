#!/usr/bin/env python3
"""Write the two documentation pages that are generated from the product itself.

    python tools/build_docs.py            docs/commands.md  from the output of ``flowcellar <command> --help``
                                          docs/metrics.md   from the metric catalogue inside the package
    python tools/build_docs.py --check    exit 1 when either page is not up to date

Nothing here is written by hand twice: the help texts live in ``src/flowcellar/cli``, the labels and limits in
``catalogue/metrics_nanopore.yaml``. Run this after changing either. Needs the package installed (any
environment that can run ``flowcellar``).
"""
