// Build the FlowCellar viewer into src/flowcellar/viewer_dist/ (shipped in the wheel; Python assembles pages from it).
//
//   node build.mjs            minified
//   node build.mjs --dev      not minified (readable stack traces)
//   node build.mjs --out DIR  write somewhere else (the build test uses this to compare two builds)
//
// Reads only: viewer/src, viewer/styles, viewer/brand and the catalogue JSON inside the package.
// Writes: viewer.core.js (one classic script, IIFE), viewer.css, favicon.svg, template.html, manifest.json.
// The same inputs give the same bytes: nothing in the output depends on the time or the machine.
import * as esbuild from 'esbuild';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '..');
const outArg = process.argv.indexOf('--out');
const dist = outArg > 0 ? path.resolve(process.argv[outArg + 1]) : path.join(repo, 'src', 'flowcellar', 'viewer_dist');
const dev = process.argv.includes('--dev');
const t0 = Date.now();
const read = p => fs.readFileSync(p, 'utf8');
const fail = m => { console.error('BUILD CHECK FAILED: ' + m); process.exit(1); };
const writeIfChanged = (p, text) => { if (!fs.existsSync(p) || read(p) !== text) fs.writeFileSync(p, text); };

// ---- 1. generated modules: catalogue copy and the logo, from tracked product files only -------------
fs.mkdirSync(path.join(here, 'src', 'gen'), { recursive: true });
let catalogueVersion = '';
{
  const cat = JSON.parse(read(path.join(repo, 'src', 'flowcellar', 'catalogue', 'metrics_nanopore.json')));
  catalogueVersion = cat.catalogue_version || '';
  // labels, "how to read" texts and the panel registry: the display copy of the catalogue, and nothing else of it
  const metrics = {};
  for (const m of (cat.metrics || []).concat(cat.derived || [])) {
    const d = m.display || {};
    if (!d.label && !d.how_to_read) continue;
    const e = {};
    if (d.label) e.label = d.label;
    if (d.short_label) e.short = d.short_label;
    if (d.how_to_read) e.how = d.how_to_read;
    if (m.unit) e.unit = m.unit;
    metrics[m.id] = e;
  }
  const sorted = {}; for (const k of Object.keys(metrics).sort()) sorted[k] = metrics[k];
  const panels = (cat.panels || []).map(p => ({ id: p.id, section: p.section, slot: p.slot, order: p.order, title: p.title }));
  const out = { version: catalogueVersion, metrics: sorted, panels, tiles: cat.tiles || {} };
  writeIfChanged(path.join(here, 'src', 'gen', 'catalogue.js'), '// generated by build.mjs from the package catalogue; do not edit\nexport default ' + JSON.stringify(out) + ';\n');
}
{
  // the single-cell and spatial add-on: the labels of its metrics and the words for what a barcode stands for
  const sc = JSON.parse(read(path.join(repo, 'src', 'flowcellar', 'sc', 'catalogue.json')));
  const metrics = {};
  for (const m of sc.metrics || []) { const d = m.display || {}; if (d.label) metrics[m.id] = { label: d.label, short: d.short_label }; }
  const sorted = {}; for (const k of Object.keys(metrics).sort()) sorted[k] = metrics[k];
  writeIfChanged(path.join(here, 'src', 'gen', 'sc_catalogue.js'), '// generated by build.mjs from the add-on\'s catalogue inside the package; do not edit\nexport default ' + JSON.stringify({ version: sc.catalogue_version || '', metrics: sorted, units: sc.units || {} }) + ';\n');
}
{
  // the horizontal lock-up for the application bar, as path data (drawn through JSX, no innerHTML)
  const svg = read(path.join(here, 'brand', 'flowcellar-lockup-dark.svg'));
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
  const g = /<g transform="([^"]+)">([\s\S]*?)<\/g>/.exec(svg);
  const top = svg.replace(g ? g[0] : '', '');
  const parts = [...top.matchAll(/<path fill="([^"]+)" d="([^"]+)"\/>/g)].map(m => ({ fill: m[1], d: m[2] }));
  const word = g ? [...g[2].matchAll(/<path fill="([^"]+)" d="([^"]+)"\/>/g)].map(m => ({ fill: m[1], d: m[2] })) : [];
  // the same drawing on a light ground (paper): its fills, in the order of the paths
  const light = read(path.join(here, 'brand', 'flowcellar-lockup.svg')), lg = /<g transform="([^"]+)">([\s\S]*?)<\/g>/.exec(light);
  const fills = text => [...text.matchAll(/<path fill="([^"]+)" d="[^"]+"\/>/g)].map(m => m[1]);
  const paper = { parts: fills(light.replace(lg ? lg[0] : '', '')), word: lg ? fills(lg[2]) : [] };
  if (paper.parts.length !== parts.length || paper.word.length !== word.length) fail('brand/flowcellar-lockup.svg and brand/flowcellar-lockup-dark.svg do not hold the same paths');
  writeIfChanged(path.join(here, 'src', 'gen', 'brand.js'), '// generated by build.mjs from brand/flowcellar-lockup-dark.svg and brand/flowcellar-lockup.svg; do not edit\nexport default ' + JSON.stringify({ viewBox, parts, wordTransform: g ? g[1] : '', word, paper }) + ';\n');
}

// ---- 2. script ---------------------------------------------------------------------------------------
const built = await esbuild.build({
  absWorkingDir: here, entryPoints: ['src/main.jsx'], bundle: true, minify: !dev, format: 'iife', write: false,
  outfile: 'viewer.core.js', target: ['firefox113', 'chrome109', 'safari16.4'], jsx: 'automatic', jsxImportSource: 'preact',
  legalComments: 'none', logLevel: 'warning', charset: 'utf8',
  // The licence asks that the notices of the bundled packages travel with every copy of the script. A one-run
  // report and a copied hub folder are such copies, and they carry no other file: so the notice is in the script.
  banner: { js: '/*! FlowCellar viewer. Copyright (C) 2026 The FlowCellar authors. Free software under the GNU General Public License, version 3 or any later version (GPL-3.0-or-later), without any warranty; the source is the repository MustafaElshani/FlowCellar on GitHub. Includes Preact, Copyright (c) 2015-present Jason Miller, and @preact/signals with @preact/signals-core, Copyright (c) 2022-present Preact Team, all under the MIT licence: Permission is hereby granted, free of charge, to any person obtaining a copy of this software and associated documentation files (the "Software"), to deal in the Software without restriction, including without limitation the rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell copies of the Software, and to permit persons to whom the Software is furnished to do so, subject to the following conditions: The above copyright notice and this permission notice shall be included in all copies or substantial portions of the Software. THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE USE OR OTHER DEALINGS IN THE SOFTWARE. */' },
});
const js = built.outputFiles[0].text;

// ---- 3. styles: the tokens (unchanged), the components, the application ------------------------------
const css = ['tokens.css', 'components.css', 'app.css'].map(f => read(path.join(here, 'styles', f))).join('\n');

// ---- 4. checks -----------------------------------------------------------------------------------------
if (/<\/script/i.test(js)) fail('the script contains </script');
if (/<!--/.test(js)) fail('the script contains <!--');
if (/<\/style/i.test(css)) fail('the stylesheet contains </style');
if (/%%[A-Z]+%%/.test(js) || /%%[A-Z]+%%/.test(css)) fail('the script or the stylesheet contains a page placeholder');
const urls = (js.match(/https?:\/\/[^\s"'`)]+/g) || []).filter(u => !/^http:\/\/www\.w3\.org\/(2000\/svg|1999\/xhtml|1998\/Math\/MathML|1999\/xlink|2000\/xmlns\/|XML\/1998\/namespace)/.test(u));
if (urls.length) fail('external URL literal in the script: ' + urls.slice(0, 3).join(', '));
if (/url\(\s*['"]?(https?:)?\/\//i.test(css) || /@import/i.test(css)) fail('the stylesheet references an external resource');
// nothing may ask the network for anything: the page reads its data from script elements only
for (const [what, re] of [['fetch(', /\bfetch\s*\(/], ['XMLHttpRequest', /XMLHttpRequest/], ['import(', /\bimport\s*\(/], ['new Worker', /new\s+(Shared)?Worker\b/], ['WebSocket', /WebSocket/], ['EventSource', /EventSource/], ['sendBeacon', /sendBeacon/], ['eval(', /\beval\s*\(/], ['new Function', /new\s+Function\b/]])
  if (re.test(js)) fail('the script uses ' + what);
// the viewer's own code never builds markup from text: data reaches the page as text nodes and attributes only
// (the framework inside the bundle has the one assignment that serves a property this code never sets)
const walk = d => fs.readdirSync(d, { withFileTypes: true }).flatMap(e => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);
for (const f of walk(path.join(here, 'src')).filter(f => /\.(js|jsx)$/.test(f))) {
  const m = /innerHTML|outerHTML|insertAdjacentHTML|dangerouslySetInnerHTML|document\.write|createContextualFragment|DOMParser|srcdoc/.exec(read(f));
  if (m) fail(path.relative(here, f) + ' uses ' + m[0]);
}
// wording that must never ship: a number shown by a bare id
if (/label missing/i.test(js) || /label missing/i.test(css)) fail('the build contains "label missing"');

// ---- 5. the page template: Python fills each placeholder exactly once (no template engine) -----------
const template = `<!doctype html><html lang="en"><head><meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="%%CSP%%">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="referrer" content="no-referrer">
<meta name="color-scheme" content="light dark">
<title>%%TITLE%%</title>
<link rel="icon" type="image/svg+xml" href="%%FAVICON%%">
<style>%%CSS%%</style></head>
<body class="fc"><div id="app">%%SUMMARY%%</div>
<script type="application/json" id="fc-boot">%%BOOT%%</script>
%%PAYLOAD%%<script>%%JS%%</script>
</body></html>
`;

// ---- 6. write ------------------------------------------------------------------------------------------
fs.mkdirSync(dist, { recursive: true });
const files = { 'viewer.core.js': js, 'viewer.css': css, 'favicon.svg': read(path.join(here, 'brand', 'favicon.svg')), 'template.html': template };
const b64 = s => createHash('sha256').update(s, 'utf8').digest('base64');
const hex = s => createHash('sha256').update(s, 'utf8').digest('hex');
const manifest = { format: 'flowcellar.viewer', catalogue: catalogueVersion, minified: !dev, files: {} };
for (const [name, text] of Object.entries(files)) {
  fs.writeFileSync(path.join(dist, name), text);
  manifest.files[name] = { bytes: Buffer.byteLength(text, 'utf8'), sha256: hex(text), csp: "'sha256-" + b64(text) + "'" };
}
manifest.placeholders = ['%%CSP%%', '%%TITLE%%', '%%FAVICON%%', '%%CSS%%', '%%SUMMARY%%', '%%BOOT%%', '%%PAYLOAD%%', '%%JS%%'];
fs.writeFileSync(path.join(dist, 'manifest.json'), JSON.stringify(manifest, null, 1) + '\n');
const kb = n => (n / 1024).toFixed(0) + ' kB';
console.log(`wrote ${path.relative(repo, dist) || dist}/: viewer.core.js ${kb(js.length)}, viewer.css ${kb(css.length)}, template.html, favicon.svg, manifest.json  (${Date.now() - t0} ms)`);
